# Load JSON dataset
raw_data_bytes = uploaded[filename]

# Decode bytes to string and remove any leading/trailing whitespace
raw_data_string = raw_data_bytes.decode('utf-8').strip()

# Find the first valid JSON start character ('{' or '[')
start_idx = -1
for i, char in enumerate(raw_data_string):
    if char == '{' or char == '[':
        start_idx = i
        break

if start_idx == -1:
    raise ValueError("Could not find a valid JSON start character ('{' or '[') in the uploaded file content.")

# Find the last valid JSON end character ('}' or ']')
end_idx = -1
for i in range(len(raw_data_string) - 1, -1, -1):
    char = raw_data_string[i]
    if char == '}' or char == ']':
        end_idx = i
        break

if end_idx == -1 or end_idx < start_idx:
    raise ValueError("Could not find a valid JSON end character ('}' or ']') corresponding to the start in the uploaded file content.")

# Extract the most likely JSON substring
json_string_to_parse = raw_data_string[start_idx : end_idx + 1]

# Further clean the extracted JSON string if it starts with '{' or '['
# by removing any non-whitespace characters that are not a quote immediately after the opening character.
if json_string_to_parse.startswith('{'):
    # Remove leading whitespace and newlines after '{' until a non-space/non-newline character is encountered
    idx = 1 # Start checking after '{'
    while idx < len(json_string_to_parse) and json_string_to_parse[idx].isspace():
        idx += 1
    if idx > 1: # If whitespace was found after '{'
        json_string_to_parse = '{' + json_string_to_parse[idx:]
elif json_string_to_parse.startswith('['):
    # Remove leading whitespace and newlines after '[' until a non-space/non-newline character is encountered
    idx = 1 # Start checking after '['
    while idx < len(json_string_to_parse) and json_string_to_parse[idx].isspace():
        idx += 1
    if idx > 1: # If whitespace was found after '['
        json_string_to_parse = '[' + json_string_to_parse[idx:]

# Now, attempt to load this cleaned substring
try:
    data = json.loads(json_string_to_parse)
except json.JSONDecodeError as e:
    # If there's still a JSONDecodeError, provide more context
    raise ValueError(f"Failed to decode JSON from file '{filename}': {e}.\nAttempted to parse this string (first 200 chars):\n'{json_string_to_parse[:200]}'...") from e

# Create a dictionary for quick student information lookup
students = {
    student["student_id"]: student
    for student in data["students"]
}

# Extract performance data
records = []

for student in data["performance_tracker"]:

    student_id = student["student_id"]

    record = {
        "student_id": student_id,
        "name": students.get(student_id, {}).get("name", "Unknown"),
        "department": students.get(student_id, {}).get("department", "Unknown"),
        "overall_attendance": student["overall_attendance_percentage"],
        "overall_average": student["overall_average_score"]
    }

    # Semester-wise features
    semesters = student.get("semesters", [])

    for sem in semesters:
        sem_no = sem["semester"]

        record[f"sem{sem_no}_attendance"] = sem["attendance_percentage"]

        scores = []

        for subject in sem.get("subjects", []):
            if "total_score" in subject:
                scores.append(subject["total_score"])

        if scores:
            record[f"sem{sem_no}_average"] = np.mean(scores)

    records.append(record)


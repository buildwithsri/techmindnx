df = pd.DataFrame(records)

print("Dataset:")
display(df.head())

# Select numerical features for anomaly detection
features = [
    "overall_attendance",
    "overall_average"
]

# Add semester features automatically
for column in df.columns:
    if "attendance" in column or "average" in column:
        if column not in features:
            features.append(column)

